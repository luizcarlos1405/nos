let current = null;

const escape = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
// Money never breaks between "R$" and its figure, nor before "mil".
const nbsp = (s) => s.replace(/R\$ (?=\d)/g, 'R$ ').replace(/(\d) mil\b/g, '$1 mil');

// The message as the site builds its others (js/whatsapp.js): blocks of lines, a blank line between them,
// *bold* as WhatsApp writes it.
const messageText = (call) => call.message.map((lines) => lines.join('\n')).join('\n\n');
const bubbleHTML = (text) => nbsp(escape(text)).replace(/\*([^*\n]+)\*/g, '<strong>$1</strong>').replace(/\n/g, '<br>');

function factHTML(f) {
  const dt = `<dt>${ICONS[f.icon]}<span class="sr-only">${f.name}</span></dt>`;
  const sub = f.sub ? `<span class="fact-sub">${nbsp(f.sub)}</span>` : '';
  if (f.href) return `<div class="fact">${dt}<dd><a class="fact-link" href="${f.href}" target="_blank" rel="noopener">${f.text}</a>${sub}</dd></div>`;
  return `<div class="fact">${dt}<dd class="fact-plain">${nbsp(f.text)}${sub}</dd></div>`;
}

function render(id) {
  const call = CALLS[id];
  if (!call || !bench) return null;
  current = call;
  bench.style.setProperty('--sector', call.sector ? `var(--role-series-${call.sector})` : 'var(--role-ink-soft)');
  $('bench-day').textContent = call.head;
  $('bench-tags').innerHTML = call.tags.map((t) => `<span class="tag">${t}</span>`).join('');
  $('bench-sr').textContent = call.sr;
  $('story-title').textContent = call.title;
  const lead = call.sector ? '<span class="dot"></span>' : ICONS.landmark;
  const group = call.group ? `<span class="fact-muted"> · ${call.group}</span>` : '';
  $('story-facts').innerHTML =
    `<div class="fact is-org"><dt>${lead}<span class="sr-only">Quem faz</span></dt><dd><span class="fact-org"><span class="fact-org-name">${call.org}</span>${group}</span><span class="fact-org-full">${call.full}</span></dd></div>` +
    call.facts.map(factHTML).join('');
  const text = messageText(call);
  $('bubble').innerHTML = bubbleHTML(text);
  $('wa-link').href = 'https://wa.me/?text=' + encodeURIComponent(text);
  document.querySelectorAll('.call-card.is-selected').forEach((c) => c.classList.remove('is-selected'));
  document.querySelector(`.call-card[data-id="${id}"]`)?.classList.add('is-selected');
  return call;
}

function scrollBench(toMessage) {
  const scroll = $('bench-scroll');
  const go = () => {
    scroll.scrollTop = 0;
    if (toMessage) scroll.scrollTop = $('message-head').getBoundingClientRect().top - scroll.getBoundingClientRect().top - 12;
  };
  go();
  requestAnimationFrame(go);
  if (document.fonts) document.fonts.ready.then(go);
}

function openCall(id, toMessage = false) {
  if (!render(id)) return;
  if (!desk.matches) {
    document.body.classList.add('sheet-open');
    bench.classList.add('is-open');
    const backdrop = $('sheet-backdrop');
    if (backdrop) backdrop.hidden = false;
  }
  scrollBench(toMessage);
}

function closeSheet() {
  document.body.classList.remove('sheet-open');
  if (bench) bench.classList.remove('is-open');
  const backdrop = $('sheet-backdrop');
  if (backdrop) backdrop.hidden = true;
}

document.querySelector('.calls')?.addEventListener('click', (e) => {
  if (e.target.closest('.call-links a, .news-agenda')) return; // the call, its page, its result open themselves
  const card = e.target.closest('.call-card');
  if (card) openCall(card.dataset.id, !!e.target.closest('.share-circle'));
});
$('bench-close')?.addEventListener('click', closeSheet);
$('sheet-backdrop')?.addEventListener('click', closeSheet);
addEventListener('keydown', (e) => { if (e.key === 'Escape') closeSheet(); });

